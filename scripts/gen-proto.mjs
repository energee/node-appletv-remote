/**
 * Compiles the MRP .proto files in src/proto into src/mrp/schema.ts, a JSON schema that
 * protobufjs loads with Root.fromJSON. Run with `npm run gen:proto` after editing a .proto file.
 */
import protobuf from 'protobufjs';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PROTO_DIR = join(ROOT, 'src', 'proto');
const OUT = join(ROOT, 'src', 'mrp', 'schema.ts');

// Many of the proto files have conflicting extension IDs or duplicate type names, so only
// the files we use are loaded. Check a new file for conflicts before adding it.
const PROTO_FILES = [
  'ProtocolMessage.proto',
  'DeviceInfoMessage.proto',
  'SendCommandMessage.proto',
  'CryptoPairingMessage.proto',
  'ClientUpdatesConfigMessage.proto',
  'SetStateMessage.proto',
  'GetStateMessage.proto',
  'NotificationMessage.proto',
  'KeyboardMessage.proto',
  'TextInputMessage.proto',
  'GetKeyboardSessionMessage.proto',
  'VolumeControlAvailabilityMessage.proto',
  'WakeDeviceMessage.proto',
  'SetConnectionStateMessage.proto',
  'SetHiliteModeMessage.proto',
  'SetNowPlayingClientMessage.proto',
  'PlaybackQueueRequestMessage.proto',
  'TransactionMessage.proto',
  'UpdateClientMessage.proto',
  'UpdateContentItemMessage.proto',
  'SendButtonEventMessage.proto',
  'SendHIDEventMessage.proto',
];

const root = new protobuf.Root();
root.resolvePath = (_origin, target) => (target.startsWith('/') ? target : join(PROTO_DIR, target));
await root.load(PROTO_FILES, { keepCase: true });
root.resolveAll();

// Sort namespace members by name so output does not depend on load order; fields keep theirs.
const sortNested = (key, value) =>
  key === 'nested' ? Object.fromEntries(Object.entries(value).sort(([a], [b]) => a.localeCompare(b))) : value;
const body = JSON.stringify(root.toJSON(), sortNested, 2);
// Typed loosely: protobufjs 8 emits an `edition` key its INamespace type does not declare.
writeFileSync(OUT, `/** Generated by scripts/gen-proto.mjs from src/proto. Do not edit by hand. */
export const MRP_SCHEMA: Record<string, unknown> = ${body};
`);
console.log(`wrote ${OUT}`);
